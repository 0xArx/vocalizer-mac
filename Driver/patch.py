# Turns BlackHole.c (GPL-3.0, github.com/ExistentialAudio/BlackHole) into the Vocalizer loopback driver:
# renamed device, plus a custom property 'vlat' (CFNumber, frames) that the Vocalizer app sets to its
# pipeline delay. The device reports it as its output latency, so video players delay the picture to match.
import sys, re
src, dst = sys.argv[1], sys.argv[2]
s = open(src).read()

header = '''// Vocalizer driver: generated by Driver/patch.py from BlackHole.c. Do not edit by hand.
#define kDriver_Name "Vocalizer"
#define kPlugIn_BundleID "com.0xarx.vocalizer.driver"
#define kPlugIn_Icon "Vocalizer.icns"
#define kHas_Driver_Name_Format false
#define kDevice_Name "Vocalizer"
#define kDevice2_Name "Vocalizer Mirror"
#define kDevice2_IsHidden true
#define kManufacturer_Name "Vocalizer"
#define kNumber_Of_Channels 2
#define kVocalizer_LatencySelector 'vlat'
#define kVocalizer_NameSelector 'vnam'
'''
s = header + s
s = s.replace('#pragma mark Prototypes', '''static UInt32 gVocalizer_Latency = 0; // frames, set by the Vocalizer app
static CFStringRef gVocalizer_Name = NULL; // display name, e.g. "Vocalizer (External Headphones)", set by the app

#pragma mark Prototypes''', 1)
assert 'gVocalizer_Latency = 0' in s

def inject(func, code):
    global s
    i = s.index(func)
    j = s.index('switch(inAddress->mSelector)', i)
    k = s.index('{', j) + 1
    s = s[:k] + '\n' + code + s[k:]

inject('static Boolean\tBlackHole_HasDeviceProperty(AudioServerPlugInDriverRef inDriver, AudioObjectID inObjectID, pid_t inClientProcessID, const AudioObjectPropertyAddress* inAddress)\n{', '''		case kVocalizer_LatencySelector:
		case kVocalizer_NameSelector:
		case kAudioObjectPropertyCustomPropertyInfoList:
			theAnswer = true;
			break;
''')
inject('static OSStatus\tBlackHole_IsDevicePropertySettable(AudioServerPlugInDriverRef inDriver, AudioObjectID inObjectID, pid_t inClientProcessID, const AudioObjectPropertyAddress* inAddress, Boolean* outIsSettable)\n{', '''		case kVocalizer_LatencySelector:
		case kVocalizer_NameSelector:
			*outIsSettable = true;
			break;
		case kAudioObjectPropertyCustomPropertyInfoList:
			*outIsSettable = false;
			break;
''')
inject('static OSStatus\tBlackHole_GetDevicePropertyDataSize(AudioServerPlugInDriverRef inDriver', '''		case kVocalizer_LatencySelector:
		case kVocalizer_NameSelector:
			*outDataSize = sizeof(CFPropertyListRef);
			break;
		case kAudioObjectPropertyCustomPropertyInfoList:
			*outDataSize = 2 * sizeof(AudioServerPlugInCustomPropertyInfo);
			break;
''')
inject('static OSStatus\tBlackHole_GetDevicePropertyData(AudioServerPlugInDriverRef inDriver', '''		case kVocalizer_LatencySelector:
		{
			FailWithAction(inDataSize < sizeof(CFPropertyListRef), theAnswer = kAudioHardwareBadPropertySizeError, Done, "Vocalizer: not enough space for vlat");
			SInt32 theLatency = (SInt32)gVocalizer_Latency;
			*((CFPropertyListRef*)outData) = CFNumberCreate(NULL, kCFNumberSInt32Type, &theLatency);
			*outDataSize = sizeof(CFPropertyListRef);
			break;
		}
		case kVocalizer_NameSelector:
		{
			FailWithAction(inDataSize < sizeof(CFPropertyListRef), theAnswer = kAudioHardwareBadPropertySizeError, Done, "Vocalizer: not enough space for vnam");
			pthread_mutex_lock(&gPlugIn_StateMutex);
			*((CFPropertyListRef*)outData) = gVocalizer_Name ? CFStringCreateCopy(NULL, gVocalizer_Name) : CFSTR(kDevice_Name);
			pthread_mutex_unlock(&gPlugIn_StateMutex);
			*outDataSize = sizeof(CFPropertyListRef);
			break;
		}
		case kAudioObjectPropertyCustomPropertyInfoList:
		{
			UInt32 theCount = inDataSize / sizeof(AudioServerPlugInCustomPropertyInfo);
			if(theCount > 2) theCount = 2;
			AudioServerPlugInCustomPropertyInfo* theInfo = (AudioServerPlugInCustomPropertyInfo*)outData;
			AudioObjectPropertySelector theSelectors[2] = { kVocalizer_LatencySelector, kVocalizer_NameSelector };
			for(UInt32 i = 0; i < theCount; ++i)
			{
				theInfo[i].mSelector = theSelectors[i];
				theInfo[i].mPropertyDataType = kAudioServerPlugInCustomPropertyDataTypeCFPropertyList;
				theInfo[i].mQualifierDataType = kAudioServerPlugInCustomPropertyDataTypeNone;
			}
			*outDataSize = theCount * sizeof(AudioServerPlugInCustomPropertyInfo);
			break;
		}
''')
inject('static OSStatus\tBlackHole_SetDevicePropertyData(AudioServerPlugInDriverRef inDriver', '''		case kVocalizer_NameSelector:
		{
			FailWithAction(inDataSize < sizeof(CFPropertyListRef), theAnswer = kAudioHardwareBadPropertySizeError, Done, "Vocalizer: wrong size for vnam");
			CFStringRef theName = *((const CFStringRef*)inData);
			FailWithAction(theName == NULL || CFGetTypeID(theName) != CFStringGetTypeID(), theAnswer = kAudioHardwareIllegalOperationError, Done, "Vocalizer: vnam must be a string");
			pthread_mutex_lock(&gPlugIn_StateMutex);
			if(gVocalizer_Name != NULL) CFRelease(gVocalizer_Name);
			gVocalizer_Name = CFStringCreateCopy(NULL, theName);
			pthread_mutex_unlock(&gPlugIn_StateMutex);
			*outNumberPropertiesChanged = 2;
			outChangedAddresses[0].mSelector = kAudioObjectPropertyName;
			outChangedAddresses[0].mScope = kAudioObjectPropertyScopeGlobal;
			outChangedAddresses[0].mElement = kAudioObjectPropertyElementMain;
			outChangedAddresses[1].mSelector = kVocalizer_NameSelector;
			outChangedAddresses[1].mScope = kAudioObjectPropertyScopeGlobal;
			outChangedAddresses[1].mElement = kAudioObjectPropertyElementMain;
			break;
		}
		case kVocalizer_LatencySelector:
		{
			FailWithAction(inDataSize < sizeof(CFPropertyListRef), theAnswer = kAudioHardwareBadPropertySizeError, Done, "Vocalizer: wrong size for vlat");
			CFNumberRef theNumber = *((const CFNumberRef*)inData);
			SInt32 theLatency = 0;
			FailWithAction(theNumber == NULL || CFGetTypeID(theNumber) != CFNumberGetTypeID() || !CFNumberGetValue(theNumber, kCFNumberSInt32Type, &theLatency), theAnswer = kAudioHardwareIllegalOperationError, Done, "Vocalizer: vlat must be a number");
			if(theLatency < 0) theLatency = 0;
			if(theLatency > 10 * 48000) theLatency = 10 * 48000;
			gVocalizer_Latency = (UInt32)theLatency;
			*outNumberPropertiesChanged = 2;
			outChangedAddresses[0].mSelector = kAudioDevicePropertyLatency;
			outChangedAddresses[0].mScope = kAudioObjectPropertyScopeOutput;
			outChangedAddresses[0].mElement = kAudioObjectPropertyElementMain;
			outChangedAddresses[1].mSelector = kVocalizer_LatencySelector;
			outChangedAddresses[1].mScope = kAudioObjectPropertyScopeGlobal;
			outChangedAddresses[1].mElement = kAudioObjectPropertyElementMain;
			break;
		}
''')

# Device latency (output scope) = the app's pipeline delay.
i = s.index('static OSStatus\tBlackHole_GetDevicePropertyData(AudioServerPlugInDriverRef inDriver')
j = s.index('case kAudioDevicePropertyLatency:', i)
k = s.index('*((UInt32*)outData) = 0;', j)
assert k - j < 600
s = s[:k] + '*((UInt32*)outData) = (inAddress->mScope == kAudioObjectPropertyScopeOutput) ? gVocalizer_Latency : 0;' + s[k + len('*((UInt32*)outData) = 0;'):]
# Device name = the app's display name when set ("Vocalizer (External Headphones)").
i = s.index('static OSStatus\tBlackHole_GetDevicePropertyData(AudioServerPlugInDriverRef inDriver')
k = s.index('*((CFStringRef*)outData) = get_device_name();', i)
s = s[:k] + '''pthread_mutex_lock(&gPlugIn_StateMutex);
                    *((CFStringRef*)outData) = gVocalizer_Name ? CFStringCreateCopy(NULL, gVocalizer_Name) : get_device_name();
                    pthread_mutex_unlock(&gPlugIn_StateMutex);''' + s[k + len('*((CFStringRef*)outData) = get_device_name();'):]
open(dst, 'w').write(s)
print("patched")
